package i18n

import (
	"fmt"
	"strings"
)

type pair struct {
	ar string
	en string
}

// T translates a key in the given locale ("ar" or "en") and replaces :name tokens.
func T(locale, key string, params ...map[string]any) string {
	p, ok := messages[key]
	if !ok {
		return key
	}
	s := p.ar
	if locale == "en" {
		s = p.en
	}
	if len(params) > 0 && params[0] != nil {
		for k, v := range params[0] {
			s = strings.ReplaceAll(s, ":"+k, fmt.Sprint(v))
		}
	}
	return s
}

